// npm run sky:data
// Builds src/_pages/personal/config/sky-catalogue.generated.ts, the compact star catalogue of the live sky
// (/personal#sky, lib/sky-engine.ts), from d3-celestial 0.7.35 (BSD-3-Clause, notice below and in the output).
// Reads node_modules/d3-celestial/data/{stars.6,constellations.lines,constellations,starnames}.json.
// Port of docs/redesign/life/sky/build-sky-data.mjs (the prototype's generator); same selection and layout.
