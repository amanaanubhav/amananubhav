import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DATA = join(ROOT, 'node_modules', 'd3-celestial', 'data');
const OUT = join(ROOT, 'src', '_pages', 'personal', 'config', 'sky-catalogue.generated.ts');
const read = (f) => JSON.parse(readFileSync(join(DATA, f), 'utf8'));
const version = JSON.parse(readFileSync(join(ROOT, 'node_modules', 'd3-celestial', 'package.json'), 'utf8')).version;

/** Stars to this V magnitude are drawn; fainter ones are kept only where a stick figure passes through them. */
const MAG_LIMIT = 5.0;
/** Greek letters only where a reader might look for them. */
const BAYER_MAG = 4.5;
/** Proper names past this are obscure IAU additions. */
const NAME_MAG = 4.0;
const wrap360 = (d) => ((d % 360) + 360) % 360;
const key = (ra, dec) => `${wrap360(ra).toFixed(2)},${dec.toFixed(2)}`;

const starsAll = read('stars.6.json').features;
const linesRaw = read('constellations.lines.json').features;
const consRaw = read('constellations.json').features;
const names = read('starnames.json');

// 1. Constellations (88 IAU + Serpens split in the data = 89 features): abbr, Latin name, English meaning, Hindi
//    name, rank, label point.
const cons = consRaw.map((f) => ({
  id: f.id,
  name: f.properties.name || f.properties.en,
  en: f.properties.en && f.properties.en !== f.properties.name ? f.properties.en : '',
  hi: f.properties.hi || '',
  rank: Number(f.properties.rank) || 3,
  ra: wrap360(f.geometry.coordinates[0]),
  dec: f.geometry.coordinates[1],
}));
const consIndex = new Map(cons.map((c, i) => [c.id, i]));

// 2. Stars: everything to MAG_LIMIT, plus any fainter star a constellation line passes through.
const byKey = new Map(starsAll.map((f) => [key(...f.geometry.coordinates), f]));
const chosen = new Map();
for (const f of starsAll) if (Number(f.properties.mag) <= MAG_LIMIT) chosen.set(key(...f.geometry.coordinates), f);
let synthetic = 0;
for (const f of linesRaw)
  for (const ls of f.geometry.coordinates)
    for (const [ra, dec] of ls) {
      const k = key(ra, dec);
      if (chosen.has(k)) continue;
      if (byKey.has(k)) chosen.set(k, byKey.get(k));
      else {
        // A line vertex with no catalogue star: a point that is never drawn (mag 9).
        chosen.set(k, { id: -1, properties: { mag: 9, bv: '0.6' }, geometry: { coordinates: [ra, dec] } });
        synthetic++;
      }
    }

const list = [...chosen.values()].sort((a, b) => Number(a.properties.mag) - Number(b.properties.mag));
const indexByKey = new Map(list.map((f, i) => [key(...f.geometry.coordinates), i]));

// Five integers per star: RA deg*50, Dec deg*50, V mag*10, round((B-V+0.5)*4), constellation index (-1 unknown).
const rows = [];
const named = [];
let drawable = 0;
list.forEach((f, i) => {
  const [ra, dec] = f.geometry.coordinates;
  const mag = Number(f.properties.mag);
  const bvNum = Number.parseFloat(f.properties.bv);
  const bv = Number.isFinite(bvNum) ? bvNum : 0.6;
  const n = f.id !== -1 ? names[f.id] : undefined;
  const c = n?.c && consIndex.has(n.c) ? consIndex.get(n.c) : -1;
  rows.push(
    Math.round(wrap360(ra) * 50) % 18000,
    Math.round(dec * 50),
    Math.round(mag * 10),
    Math.round((Math.max(-0.5, Math.min(2.5, bv)) + 0.5) * 4),
    c,
  );
  if (mag <= MAG_LIMIT) drawable++;
  const name = mag <= NAME_MAG ? n?.name || '' : '';
  const bayer = mag <= BAYER_MAG && n?.bayer ? n.bayer : '';
  if (name || bayer) named.push([i, name, bayer]);
});

// 3. Constellation figures as polylines of star indices.
const figures = linesRaw.map((f) => [
  consIndex.has(f.id) ? consIndex.get(f.id) : -1,
  f.geometry.coordinates.map((ls) => ls.map(([ra, dec]) => indexByKey.get(key(ra, dec)))),
]);

const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lines = (items, per) => {
  const out = [];
  for (let i = 0; i < items.length; i += per) out.push(`    ${items.slice(i, i + per).join(', ')},`);
  return out.join('\n');
};
const starRows = [];
for (let i = 0; i < rows.length; i += 5) starRows.push(rows.slice(i, i + 5).join(', '));

