// Serialises plain data into the TypeScript literal style of the generated modules (single quotes,
// two-space indent, trailing commas), and writes modules with the GENERATED header.
import { writeFileSync } from 'node:fs';

const IDENT = /^[A-Za-z_$][\w$]*$/;
const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** Arrays whose items are all numbers print inline: [1000, 1250]. */
const isFlatNumbers = (v) => Array.isArray(v) && v.every((x) => typeof x === 'number');

/** Small objects of scalars print on one line: { x: 1, y: 2, name: 'Manang' }. */
function isInlineObject(v) {
  if (!v || typeof v !== 'object' || Array.isArray(v)) return false;
  const entries = Object.entries(v).filter(([, x]) => x !== undefined);
  return entries.every(([, x]) => ['number', 'string', 'boolean'].includes(typeof x)) && entries.length <= 10;
}

export function toTs(value, indent = '') {
  const inner = `${indent}  `;
  if (value === null) return 'null';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '0';
  if (typeof value === 'string') return quote(value);
  if (typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    if (isFlatNumbers(value)) return `[${value.join(', ')}]`;
    // Arrays of number tuples (star lists) pack several tuples per line.
    if (value.every(isFlatNumbers)) {
      const lines = [];
      for (let i = 0; i < value.length; i += 6) {
        lines.push(`${inner}${value.slice(i, i + 6).map((t) => `[${t.join(', ')}]`).join(', ')},`);
      }
      return `[\n${lines.join('\n')}\n${indent}]`;
    }
    return `[\n${value.map((v) => `${inner}${toTs(v, inner)},`).join('\n')}\n${indent}]`;
  }
  const entries = Object.entries(value).filter(([, v]) => v !== undefined);
  const key = (k) => (IDENT.test(k) ? k : quote(k));
  if (isInlineObject(value)) return `{ ${entries.map(([k, v]) => `${key(k)}: ${toTs(v)}`).join(', ')} }`;
  return `{\n${entries.map(([k, v]) => `${inner}${key(k)}: ${toTs(v, inner)},`).join('\n')}\n${indent}}`;
}

export const GENERATED_HEADER =
  '/* GENERATED by scripts/posters/build-posters.mjs (npm run gen:posters) from public/data/. Do not edit. */';

/** Writes a module and returns its size in bytes. */
export function writeModule(path, text) {
  writeFileSync(path, text);
  return Buffer.byteLength(text);
}
