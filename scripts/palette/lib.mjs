const HEX = /^#[0-9A-F]{6}$/;

// ---------------------------------------------------------------------------------------------------------------------
// The extended block (PALETTE-SPEC §4, §8.1): `extended.<theme>.<group>.<name>`. Groups only organise the file; every
// name is a global kebab-case token that becomes `--<name>`. Both themes hold the same groups, names, kinds, array
// lengths and stop positions, so every token and every indexed member exists in both themes.

/** §8.1 value grammar. Anything else (long CSS strings, literal triplets inside rgb()) is rejected by loadPalette(). */
export const EXT_GRAMMAR = {
  /** '#9F89B8' -> `--c-name: 159 137 184;` `--name: #9F89B8;` and a Tailwind colour. */
  solid: HEX,
  /** 'var(--signal-line)': a core role, an extended solid or alias, or a ramp member. Emitted like a solid. */
  alias: /^var\(--([a-z0-9-]+)\)$/,
  /** 'rgb(var(--c-aqua) / var(--alpha-wash))': a colour at a ladder alpha, emitted verbatim. */
  composite: /^rgb\(var\(--c-([a-z0-9-]+)\) \/ (?:var\(--(alpha-[a-z0-9-]+)\)|(0|1|0?\.\d+))\)$/,
  /** 0.86, '24px', '1.5', 'transparent', emitted verbatim. */
  scalar: /^(?:\d+(?:\.\d+)?(?:px|rem|em|%|deg|ms|s)?|transparent)$/,
};
const STOP_AT = /^\d+(?:\.\d+)?%(?: \d+(?:\.\d+)?%)?$/;
const KEBAB = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

/** Names the core block of tokens.css already defines. */
export const RESERVED_NAMES = [...ROLES, 'ink-contour', 'ink-contour-index', 'shadow-float', 'grain-opacity'];

/** Ramps with a fixed length: the shader, the legend and the chart code index into them. */
export const RAMP_LENGTHS = { 'map-hypso': 6, 'map-temp': 6, 'chart-sequential': 5, 'chart-diverging': 7 };

