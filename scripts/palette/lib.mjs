const isPlainObject = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);
const isStop = (value) =>
  isPlainObject(value) &&
  Object.keys(value).length === 2 &&
  typeof value.color === 'string' &&
  typeof value.at === 'string';

/** 'solid' | 'alias' | 'composite' | 'scalar' | 'ramp' | 'stops', or 'bad' outside the grammar. */
export function extendedKind(value) {
  if (Array.isArray(value)) {
    if (value.length > 0 && value.every((item) => typeof item === 'string')) return 'ramp';
    if (value.length > 0 && value.every(isStop)) return 'stops';
    return 'bad';
  }
  if (typeof value === 'number') return Number.isFinite(value) ? 'scalar' : 'bad';
  if (typeof value !== 'string') return 'bad';
  if (EXT_GRAMMAR.solid.test(value)) return 'solid';
  if (EXT_GRAMMAR.alias.test(value)) return 'alias';
  if (EXT_GRAMMAR.composite.test(value)) return 'composite';
  if (EXT_GRAMMAR.scalar.test(value)) return 'scalar';
  return 'bad';
}

/** The extended tokens of one theme in file order: [name, value, kind, group]. */
export function extendedEntries(palette, theme) {
  const out = [];
  for (const [group, tokens] of Object.entries(palette.extended[theme])) {
    for (const [name, value] of Object.entries(tokens)) out.push([name, value, extendedKind(value), group]);
  }
  return out;
}

/** 'map-route-casing' -> 'routeCasing' (the StoryThemeColors field of a map token). */
export const storyField = (name) => name.replace(/^map-/, '').replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const kebabCase = (field) => field.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const indexCache = new WeakMap();

/** Name lookup for one theme: the extended entries plus the members of ramps and stop lists (`map-hypso-1`). */
function themeIndex(palette, theme) {
  let cached = indexCache.get(palette);
  if (!cached) indexCache.set(palette, (cached = {}));
  if (cached[theme]) return cached[theme];
  const entries = new Map();
  const members = new Map();
  for (const [name, value, kind, group] of extendedEntries(palette, theme)) {
    entries.set(name, { value, kind, group });
    if (kind === 'ramp' || kind === 'stops') {
      value.forEach((item, i) => {
        members.set(`${name}-${i + 1}`, { parent: name, kind, value: kind === 'ramp' ? item : item.color });
      });
    }
  }
  return (cached[theme] = { entries, members });
}

/**
 * Follows a colour reference to its hex. Colour names are the core roles, the extended solids and aliases, and ramp
 * members; composites, scalars and stop lists are not colours. Throws a readable error on an unknown name, a
 * non-colour or a cycle.
 */
function hexOf(palette, theme, name, chain = []) {
  if (chain.includes(name)) throw new Error(`alias cycle ${[...chain, name].map((n) => `--${n}`).join(' -> ')}`);
  if (ROLES.includes(name)) return palette[theme][name];
  const { entries, members } = themeIndex(palette, theme);
  const entry = entries.get(name);
  if (entry) {
    if (entry.kind === 'solid') return entry.value;
    if (entry.kind === 'alias') return hexOf(palette, theme, EXT_GRAMMAR.alias.exec(entry.value)[1], [...chain, name]);
    if (entry.kind === 'bad') throw new Error(`--${name} has a value outside the grammar`);
    throw new Error(`--${name} is a ${entry.kind}, not a solid colour`);
  }
  const member = members.get(name);
  if (member?.kind === 'ramp') {
    if (HEX.test(member.value)) return member.value;
    const alias = EXT_GRAMMAR.alias.exec(member.value);
    if (alias) return hexOf(palette, theme, alias[1], [...chain, name]);
    throw new Error(`--${name} (member of ${member.parent}) is not a solid colour`);
  }
  if (member) throw new Error(`--${name} is a gradient stop of ${member.parent}, not a solid colour`);
  throw new Error(`--${name} is not defined in ${theme}`);
}

function alphaOf(palette, theme, name) {
  const entry = themeIndex(palette, theme).entries.get(name);
  if (!entry) throw new Error(`--${name} is not defined in ${theme}`);
  if (typeof entry.value !== 'number' || entry.value < 0 || entry.value > 1) {
    throw new Error(`--${name} is not an alpha (a number from 0 to 1)`);
  }
  return entry.value;
}

/** Resolves a colour value of the grammar to { hex, alpha }; 'transparent' resolves to { hex: null, alpha: 0 }. */
function colourOf(palette, theme, value) {
  if (value === 'transparent') return { hex: null, alpha: 0 };
  if (HEX.test(value)) return { hex: value, alpha: 1 };
  const alias = EXT_GRAMMAR.alias.exec(value);
  if (alias) return { hex: hexOf(palette, theme, alias[1]), alpha: 1 };
  const composite = EXT_GRAMMAR.composite.exec(value);
  if (composite) {
    const [, ref, alphaRef, literal] = composite;
    return { hex: hexOf(palette, theme, ref), alpha: alphaRef ? alphaOf(palette, theme, alphaRef) : Number(literal) };
  }
  throw new Error(`${JSON.stringify(value)} is not a colour (hex, var(--x), rgb(var(--c-x) / var(--alpha-y)) or transparent)`);
}

/** Hex of any colour token of a theme: a core role, an extended solid or alias, or a ramp member (`map-hypso-1`). */
export function tokenHex(palette, theme, name) {
  return hexOf(palette, theme, name);
}

function grammarHint(value) {
  if (typeof value === 'string' && /gradient\(/.test(value)) return '; write gradients as a stop list [{ "color", "at" }]';
  if (typeof value === 'string' && /(?:rgba?|hsla?)\(\s*\d/.test(value)) {
    return '; literal triplets are not allowed: reference a solid, rgb(var(--c-<name>) / var(--alpha-<step>))';
  }
  if (typeof value === 'string' && /^#[0-9a-f]{6}$/i.test(value)) return '; hex is written uppercase #RRGGBB';
  return '';
}

/** Checks one token's value against the grammar and resolves every reference it makes (throws on the first problem). */
function checkValue(palette, theme, name, value, kind) {
  if (kind === 'bad') {
    throw new Error(
      `${JSON.stringify(value)} is outside the grammar (hex, var(--x), rgb(var(--c-x) / var(--alpha-y)), a scalar, ` +
        `a ramp of colours or a stop list)${grammarHint(value)}`,
    );
  }
  if (name.startsWith('alpha-') && (typeof value !== 'number' || value < 0 || value > 1)) {
    throw new Error(`alpha steps are numbers from 0 to 1, got ${JSON.stringify(value)}`);
  }
  if (kind === 'alias' || kind === 'composite') colourOf(palette, theme, value);
  if (kind === 'ramp') {
    value.forEach((item, i) => {
      if (!HEX.test(item) && !EXT_GRAMMAR.alias.test(item)) {
        throw new Error(`ramp item ${i + 1} ${JSON.stringify(item)} must be a hex or a var() alias${grammarHint(item)}`);
      }
      hexOf(palette, theme, `${name}-${i + 1}`);
    });
    const expected = RAMP_LENGTHS[name];
    if (expected && value.length !== expected) throw new Error(`needs ${expected} ramp stops, has ${value.length}`);
  }
  if (kind === 'stops') {
    value.forEach((stop, i) => {
      if (!STOP_AT.test(stop.at)) throw new Error(`stop ${i + 1} position ${JSON.stringify(stop.at)} must be "N%" or "N% M%"`);
      try {
        colourOf(palette, theme, stop.color);
      } catch (err) {
        throw new Error(`stop ${i + 1}: ${err.message}${grammarHint(stop.color)}`);
      }
    });
  }
}

/** Validates `raw.extended` (PALETTE-SPEC §8.2.1). Throws one readable error that lists every problem found. */
function validateExtended(raw) {
  const ext = raw.extended;
  if (!isPlainObject(ext)) throw new Error('palette.json: missing "extended" (the night and day token groups, §4)');
  const problems = [];
  for (const theme of Object.keys(ext)) {
    if (!THEMES.includes(theme)) problems.push(`extended.${theme}: unknown theme (expected ${THEMES.join(', ')})`);
  }
  for (const theme of THEMES) {
    if (!isPlainObject(ext[theme])) {
      problems.push(`extended.${theme}: missing (both themes hold the same groups)`);
      continue;
    }
    for (const [group, tokens] of Object.entries(ext[theme])) {
      if (!KEBAB.test(group)) problems.push(`extended.${theme}.${group}: group names are kebab-case`);
      if (!isPlainObject(tokens)) problems.push(`extended.${theme}.${group}: a group is an object of { name: value }`);
    }
  }
  if (problems.length) throw new Error(`palette.json "extended":\n  - ${problems.join('\n  - ')}`);

  // R4: identical deep key sets, the same kind per token, equal array lengths and shared stop positions
  const [a, b] = THEMES;
  const kindClass = (kind) => (kind === 'solid' || kind === 'alias' ? 'colour' : kind);
  for (const [from, to] of [
    [a, b],
    [b, a],
  ]) {
    for (const group of Object.keys(ext[from])) {
      if (!(group in ext[to])) {
        problems.push(`extended.${to}: missing group "${group}" (defined in ${from}; both themes hold the same keys)`);
        continue;
      }
      for (const name of Object.keys(ext[from][group])) {
        if (!(name in ext[to][group])) problems.push(`extended.${to}.${group}: missing "${name}" (defined in ${from})`);
      }
    }
  }
  for (const [group, tokens] of Object.entries(ext[a])) {
    for (const [name, value] of Object.entries(tokens)) {
      const other = ext[b][group]?.[name];
      if (other === undefined) continue;
      const [ka, kb] = [extendedKind(value), extendedKind(other)];
      if (ka === 'bad' || kb === 'bad') continue;
      if (kindClass(ka) !== kindClass(kb)) {
        problems.push(`extended.*.${group}.${name}: ${a} is a ${kindClass(ka)}, ${b} a ${kindClass(kb)} (one kind in both themes)`);
      } else if (Array.isArray(value) && value.length !== other.length) {
        problems.push(`extended.*.${group}.${name}: ${a} has ${value.length} items, ${b} has ${other.length} (indexed tokens exist in both themes)`);
      } else if (ka === 'stops') {
        value.forEach((stop, i) => {
          if (stop.at !== other[i].at) {
            problems.push(`extended.*.${group}.${name}: stop ${i + 1} sits at "${stop.at}" in ${a} but "${other[i].at}" in ${b} (SVG stops share offsets)`);
          }
        });
      }
    }
  }

  // names, grammar and references, per theme
  for (const theme of THEMES) {
    const seen = new Map();
    for (const [group, tokens] of Object.entries(ext[theme])) {
      for (const [name, value] of Object.entries(tokens)) {
        const where = `extended.${theme}.${group}.${name}`;
        if (!KEBAB.test(name)) problems.push(`${where}: token names are kebab-case`);
        if (name.startsWith('c-')) problems.push(`${where}: names may not start with "c-" (reserved for --c-<name> triplets)`);
        if (RESERVED_NAMES.includes(name)) problems.push(`${where}: collides with the core token --${name}`);
        if (seen.has(name)) problems.push(`${where}: also defined in group "${seen.get(name)}" (token names are global)`);
        seen.set(name, group);
        try {
          checkValue(raw, theme, name, value, extendedKind(value));
        } catch (err) {
          problems.push(`${where}: ${err.message}`);
        }
      }
    }
    for (const [member, { parent }] of themeIndex(raw, theme).members) {
      if (seen.has(member) || RESERVED_NAMES.includes(member)) {
        problems.push(`extended.${theme}: --${member} (an indexed member of ${parent}) collides with another token`);
      }
    }
    const map = ext[theme].map;
    if (!isPlainObject(map)) {
      problems.push(`extended.${theme}: missing group "map" (the story map, STORY_THEME)`);
    } else {
      for (const [name, value] of Object.entries(map)) {
        if (!name.startsWith('map-')) problems.push(`extended.${theme}.map.${name}: map tokens are named map-<field>`);
        if (extendedKind(value) === 'stops') problems.push(`extended.${theme}.map.${name}: the map group holds no stop lists`);
      }
      for (const field of STORY_FIELDS) {
        if (!(`map-${kebabCase(field)}` in map)) problems.push(`extended.${theme}.map: missing map-${kebabCase(field)} (StoryThemeColors.${field})`);
      }
    }
  }
  if (problems.length) {
    throw new Error(`palette.json "extended" has ${problems.length} problem(s):\n  - ${problems.join('\n  - ')}`);
  }
}

/** Reads and validates scripts/palette/palette.json. Throws with a readable message on any shape error. */
export function loadPalette() {
  return validatePalette(JSON.parse(readFileSync(resolve(SCRIPT_DIR, 'palette.json'), 'utf8')));
}

/** Validates a parsed palette (core roles, contour, effects, then the extended block) and returns it unchanged. */
export function validatePalette(raw) {
  for (const theme of THEMES) {
    const tokens = raw[theme];
    if (!tokens || typeof tokens !== 'object') throw new Error(`palette.json: missing "${theme}"`);
    const keys = Object.keys(tokens);
    const missing = ROLES.filter((role) => !keys.includes(role));
    const extra = keys.filter((key) => !ROLES.includes(key));
    if (missing.length || extra.length) {
      throw new Error(
        `palette.json "${theme}": roles must be exactly §B.1` +
          (missing.length ? `; missing ${missing.join(', ')}` : '') +
          (extra.length ? `; unexpected ${extra.join(', ')}` : ''),
      );
    }
    for (const role of ROLES) {
      if (!HEX.test(tokens[role])) {
        throw new Error(`palette.json "${theme}.${role}": expected uppercase #RRGGBB, got ${tokens[role]}`);
      }
    }
    const contour = raw.contour?.[theme];
    if (!Array.isArray(contour) || contour.length !== 5) {
      throw new Error(`palette.json "contour.${theme}": expected [r, g, b, minorAlpha, indexAlpha]`);
    }
    const fx = raw.effects?.[theme];
    if (!fx || !fx['shadow-float'] || !fx['grain-opacity'] || !fx['color-scheme']) {
      throw new Error(`palette.json "effects.${theme}": expected shadow-float, grain-opacity, color-scheme`);
    }
  }
  validateExtended(raw);
  return raw;
}

/** Every extended token of a theme resolved: hex for colours, { hex, alpha } for composites, the value for scalars,
 * hex[] for ramps and { hex, alpha, at, ref }[] for stop lists ('transparent' has hex null). */
export function resolveExtended(palette, theme) {
  const out = {};
  for (const [name, value, kind] of extendedEntries(palette, theme)) {
    if (kind === 'solid' || kind === 'alias') out[name] = hexOf(palette, theme, name);
    else if (kind === 'composite') out[name] = colourOf(palette, theme, value);
    else if (kind === 'scalar') out[name] = value;
    else if (kind === 'ramp') out[name] = value.map((_, i) => hexOf(palette, theme, `${name}-${i + 1}`));
    else if (kind === 'stops') {
      out[name] = value.map((stop) => ({ ...colourOf(palette, theme, stop.color), at: stop.at, ref: stop.color }));
    }
  }
  return out;
}

/** Extended colours (solids, aliases and ramp members) resolved to hex, in file order: [name, hex]. */
export function extendedSolids(palette, theme) {
  const out = [];
  for (const [name, value, kind] of extendedEntries(palette, theme)) {
    if (kind === 'solid' || kind === 'alias') out.push([name, hexOf(palette, theme, name)]);
    else if (kind === 'ramp') value.forEach((_, i) => out.push([`${name}-${i + 1}`, hexOf(palette, theme, `${name}-${i + 1}`)]));
  }
  return out;
}

/** Composite tokens resolved to { hex, alpha }, in file order: [name, { hex, alpha }]. */
export function extendedComposites(palette, theme) {
  return extendedEntries(palette, theme)
    .filter(([, , kind]) => kind === 'composite')
    .map(([name, value]) => [name, colourOf(palette, theme, value)]);
}

/** The alpha ladder (`alpha-*` tokens), in file order: [name, alpha]. */
export function alphaLadder(palette, theme) {
  return extendedEntries(palette, theme)
    .filter(([name]) => name.startsWith('alpha-'))
    .map(([name, value]) => [name, value]);
}

/** '#0E2231' -> [14, 34, 49] */
export function hexToRgb255(hex) {
  const n = Number.parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** WCAG 2.x relative luminance of an sRGB hex. */
export function luminance(hex) {
  const [r, g, b] = hexToRgb255(hex).map((channel) => {
    const c = channel / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG 2.x contrast ratio between two hexes (order does not matter). */
export function contrast(a, b) {
  const la = luminance(a);
  const lb = luminance(b);
  const [hi, lo] = la >= lb ? [la, lb] : [lb, la];
  return (hi + 0.05) / (lo + 0.05);
}

const alpha = (value) => Number(value).toFixed(2);

const solidLine = (name, value) => {
  const alias = EXT_GRAMMAR.alias.exec(value);
  const triplet = alias ? `var(--c-${alias[1]})` : hexToRgb255(value).join(' ');
  return `${`  --c-${name}: ${triplet};`.padEnd(34)} --${name}: ${value};`;
};

/**
 * The extended custom properties of one theme (§8.1), appended inside its block of tokens.css after the core lines:
 * solids and aliases as `--c-<name>` + `--<name>`, composites and scalars verbatim, ramps as `--<name>-<n>` solids,
 * stop lists as `--<name>` (for `linear-gradient(<angle>, var(--<name>))`) plus `--<name>-<n>` (for SVG stop-color).
 */
export function renderExtendedLines(palette, theme) {
  const lines = [];
  for (const [name, value, kind] of extendedEntries(palette, theme)) {
    if (kind === 'solid' || kind === 'alias') lines.push(solidLine(name, value));
    else if (kind === 'composite' || kind === 'scalar') lines.push(`  --${name}: ${value};`);
    else if (kind === 'ramp') value.forEach((item, i) => lines.push(solidLine(`${name}-${i + 1}`, item)));
    else if (kind === 'stops') {
      lines.push(`  --${name}: ${value.map((stop) => `${stop.color} ${stop.at}`).join(', ')};`);
      value.forEach((stop, i) => lines.push(`  --${name}-${i + 1}: ${stop.color};`));
    }
  }
  return lines;
}

/** The exact text of src/_app/styles/tokens.css (§B.2): the core lines, unchanged, then the extended lines (§8.2.3). */
export function renderTokensCss(palette) {
  const block = (theme) => {
    const tokens = palette[theme];
    const lines = ROLES.map((role) => {
      const triplet = `  --c-${role}: ${hexToRgb255(tokens[role]).join(' ')};`;
      return `${triplet.padEnd(30)} --${role}: ${tokens[role]};`;
    });
    const [r, g, b, minor, index] = palette.contour[theme];
    const fx = palette.effects[theme];
    lines.push(
      `  --ink-contour: rgb(${r} ${g} ${b} / ${alpha(minor)});`,
      `  --ink-contour-index: rgb(${r} ${g} ${b} / ${alpha(index)});`,
      `  --shadow-float: ${fx['shadow-float']};`,
      `  --grain-opacity: ${fx['grain-opacity']};`,
      `  color-scheme: ${fx['color-scheme']};`,
      ...renderExtendedLines(palette, theme),
    );
    return lines.join('\n');
  };
  return [
    GENERATED_HEADER,
    ':root,',
    ":root[data-theme='night'] {",
    block('night'),
    '}',
    ":root[data-theme='day'] {",
    block('day'),
    '}',
    '',
  ].join('\n');
}

/**
 * The Tailwind colour map (src/_app/styles/tailwind-colors.json, §8.4): the 15 core roles (ground-sky also as the
 * legacy `sky`) and every extended colour (solids, aliases, ramp members), each `rgb(var(--c-<name>) / <alpha-value>)`
 * so opacity modifiers work. Composites, scalars and stop lists are not Tailwind colours.
 */
export function renderTailwindColors(palette) {
  const colour = (name) => `rgb(var(--c-${name}) / <alpha-value>)`;
  const map = {};
  for (const role of ROLES) map[role === 'ground-sky' ? 'sky' : role] = colour(role);
  map['ground-sky'] = colour('ground-sky');
  for (const [name] of extendedSolids(palette, THEMES[0])) map[name] = colour(name);
  return map;
}

/** StoryThemeColors data per theme: `extended.<theme>.map` with camel-cased field names (resolveExtended values). */
export function renderStoryTheme(palette) {
  const data = {};
  for (const theme of THEMES) {
    const resolved = resolveExtended(palette, theme);
    data[theme] = Object.fromEntries(Object.keys(palette.extended[theme].map).map((name) => [storyField(name), resolved[name]]));
  }
  return data;
}

const HEX_TYPE = '`#${string}`';
const tsKey = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`);
function tsValue(value) {
  if (typeof value === 'string') return `'${value}'`;
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) return `[${value.map(tsValue).join(', ')}]`;
  return `{ ${Object.entries(value)
    .map(([key, item]) => `${tsKey(key)}: ${tsValue(item)}`)
    .join(', ')} }`;
}
function tsType(kind, value) {
  if (kind === 'solid' || kind === 'alias') return HEX_TYPE;
  if (kind === 'composite') return 'ThemeComposite';
  if (kind === 'ramp') return `readonly [${value.map(() => HEX_TYPE).join(', ')}]`;
  return typeof value === 'number' ? 'number' : 'string';
}

/** The §8.2.4 additions to palette.ts: ExtendedRole, THEME_EXTENDED, THEME_ALPHA, THEME_COMPOSITE and STORY_THEME. */
function renderExtendedTs(palette) {
  const first = THEMES[0];
  const union = (names) => names.map((name) => `  | '${name}'`).join('\n');
  const entries = (pairs) => pairs.map(([key, value]) => `    ${tsKey(key)}: ${tsValue(value)},`).join('\n');
  const perTheme = (pairsOf) => THEMES.map((theme) => `  ${theme}: {\n${entries(pairsOf(theme))}\n  },`).join('\n');
  const story = renderStoryTheme(palette);
  const mapFields = extendedEntries(palette, first)
    .filter(([, , , group]) => group === 'map')
    .map(([name, value, kind]) => `  readonly ${tsKey(storyField(name))}: ${tsType(kind, value)};`);
  return `
/**
 * A colour at an alpha, resolved for WebGL and canvas. In CSS the same token reads
 * \`rgb(var(--c-<role>) / var(--alpha-<step>))\`.
 */
export interface ThemeComposite {
  readonly hex: ${HEX_TYPE};
  readonly alpha: number;
}

/**
 * Extended colours (PALETTE-SPEC §4): every hex or var() alias of \`extended.<theme>\` plus each ramp member as
 * \`<ramp>-<n>\`. CSS: \`var(--<name>)\` or \`rgb(var(--c-<name>) / var(--alpha-<step>))\`; Tailwind: \`bg-<name>\`.
 */
export type ExtendedRole =
${union(extendedSolids(palette, first).map(([name]) => name))};

/** Resolved hexes of the extended colours, per theme (aliases followed to their source). */
export const THEME_EXTENDED: Readonly<Record<ThemeName, Readonly<Record<ExtendedRole, ${HEX_TYPE}>>>> = {
${perTheme((theme) => extendedSolids(palette, theme))}
};

/** The alpha ladder (\`--alpha-*\`, PALETTE-SPEC §4.5): the only alphas a wash, rim, scrim or glass may use. */
export type AlphaStep =
${union(alphaLadder(palette, first).map(([name]) => name))};

/** Alpha ladder values, per theme. */
export const THEME_ALPHA: Readonly<Record<ThemeName, Readonly<Record<AlphaStep, number>>>> = {
${perTheme((theme) => alphaLadder(palette, theme))}
};

/** Composite tokens: a colour at a ladder alpha (washes, glass light, scrims, the terminal rims, the route casing). */
export type CompositeRole =
${union(extendedComposites(palette, first).map(([name]) => name))};

/** Composite tokens resolved to { hex, alpha }, per theme, for WebGL uniforms and canvas drawing. */
export const THEME_COMPOSITE: Readonly<Record<ThemeName, Readonly<Record<CompositeRole, ThemeComposite>>>> = {
${perTheme((theme) => extendedComposites(palette, theme))}
};

/**
 * The home story map's colours (\`extended.<theme>.map\`, camel-cased: \`map-route-casing\` -> \`routeCasing\`), for the
 * relief scene's uniforms and the DOM legend. \`hypso\` holds the 800 / 2000 / 3500 / 4500 / 5500 / 7000 m stops and
 * \`temp\` the -25 / -10 / 0 / +5 / +12 / +22 °C stops; \`minor\` and \`index\` are contour alphas, \`shade\` the hillshade.
 */
export interface StoryThemeTokens {
${mapFields.join('\n')}
}

/** StoryThemeColors data per theme, for STORY_PALETTE in story-palette.ts (PALETTE-SPEC §8.4, R28). */
export const STORY_THEME: Readonly<Record<ThemeName, StoryThemeTokens>> = {
${perTheme((theme) => Object.entries(story[theme]))}
};
`;
}

