export const GENERATED_HEADER = '/* GENERATED by scripts/palette/emit.mjs. Do not edit. */';

/** The §B.1 role keys, in token order. palette.json must hold exactly these for both themes. */
export const ROLES = [
  'ground',
  'surface',
  'surface-2',
  'ground-sky',
  'line',
  'line-strong',
  'ink',
  'ink-muted',
  'signal',
  'signal-line',
  'on-signal',
  'water',
  'success',
  'warning',
  'error',
];

export const THEMES = ['night', 'day'];

const HEX = /^#[0-9A-F]{6}$/;

/** Reads and validates scripts/palette/palette.json. Throws with a readable message on any shape error. */
export function loadPalette() {
  const raw = JSON.parse(readFileSync(resolve(SCRIPT_DIR, 'palette.json'), 'utf8'));
  for (const theme of THEMES) {
    const tokens = raw[theme];
    if (!tokens || typeof tokens !== 'object') throw new Error(`palette.json: missing "${theme}"`);
    const keys = Object.keys(tokens);
    const missing = ROLES.filter((role) => !keys.includes(role));
    const extra = keys.filter((key) => !ROLES.includes(key));
    if (missing.length || extra.length) {
      throw new Error(
        `palette.json "${theme}": roles must be exactly §B.1` +
          (missing.length ? `; missing ${missing.join(', ')}` : '') +
          (extra.length ? `; unexpected ${extra.join(', ')}` : ''),
      );
    }
    for (const role of ROLES) {
      if (!HEX.test(tokens[role])) {
        throw new Error(`palette.json "${theme}.${role}": expected uppercase #RRGGBB, got ${tokens[role]}`);
      }
    }
    const contour = raw.contour?.[theme];
    if (!Array.isArray(contour) || contour.length !== 5) {
      throw new Error(`palette.json "contour.${theme}": expected [r, g, b, minorAlpha, indexAlpha]`);
    }
    const fx = raw.effects?.[theme];
    if (!fx || !fx['shadow-float'] || !fx['grain-opacity'] || !fx['color-scheme']) {
      throw new Error(`palette.json "effects.${theme}": expected shadow-float, grain-opacity, color-scheme`);
    }
  }
  return raw;
}

/** '#0E2231' -> [14, 34, 49] */
export function hexToRgb255(hex) {
  const n = Number.parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** WCAG 2.x relative luminance of an sRGB hex. */
export function luminance(hex) {
  const [r, g, b] = hexToRgb255(hex).map((channel) => {
    const c = channel / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG 2.x contrast ratio between two hexes (order does not matter). */
export function contrast(a, b) {
  const la = luminance(a);
  const lb = luminance(b);
  const [hi, lo] = la >= lb ? [la, lb] : [lb, la];
  return (hi + 0.05) / (lo + 0.05);
}

const alpha = (value) => Number(value).toFixed(2);

/** The exact text of src/_app/styles/tokens.css (§B.2). */
export function renderTokensCss(palette) {
  const block = (theme) => {
    const tokens = palette[theme];
    const lines = ROLES.map((role) => {
      const triplet = `  --c-${role}: ${hexToRgb255(tokens[role]).join(' ')};`;
      return `${triplet.padEnd(30)} --${role}: ${tokens[role]};`;
    });
    const [r, g, b, minor, index] = palette.contour[theme];
    const fx = palette.effects[theme];
    lines.push(
      `  --ink-contour: rgb(${r} ${g} ${b} / ${alpha(minor)});`,
      `  --ink-contour-index: rgb(${r} ${g} ${b} / ${alpha(index)});`,
      `  --shadow-float: ${fx['shadow-float']};`,
      `  --grain-opacity: ${fx['grain-opacity']};`,
      `  color-scheme: ${fx['color-scheme']};`,
    );
    return lines.join('\n');
  };
  return [
    GENERATED_HEADER,
    ':root,',
    ":root[data-theme='night'] {",
    block('night'),
    '}',
    ":root[data-theme='day'] {",
    block('day'),
    '}',
    '',
  ].join('\n');
}

/** The exact text of src/shared/config/palette.ts (§B.2), keeping the deprecated PALETTE, PaletteColor and rgba verbatim. */
